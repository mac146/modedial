import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";

const root = resolve(__dirname, "..");
const read = (p: string) => readFileSync(resolve(root, p), "utf8").replace(/\r\n/g, "\n");

describe("landing page", () => {
  it("modes-data.js matches modes/modes.json (run `node scripts/build-site.mjs` if this fails)", () => {
    const expected = `// Generated by scripts/build-site.mjs from modes/modes.json. Do not edit.\nwindow.MODEDIAL_MODES = ${JSON.stringify(JSON.parse(read("modes/modes.json")), null, 2)};\n`;
    expect(read("site/modes-data.js")).toBe(expected);
  });

  it("every local file the page references exists", () => {
    const html = read("site/index.html");
    const refs = [...html.matchAll(/(?:src|href)="(?!https?:|#|mailto:)([^"]+)"/g)].map((m) => m[1]!)
      .concat([...html.matchAll(/url\(([^)]+\.ttf)\)/g)].map((m) => m[1]!));
    expect(refs.length).toBeGreaterThan(0);
    for (const r of refs) expect(existsSync(resolve(root, "site", r.replace(/^\//, ""))), r).toBe(true);
  });

  it("has favicons: SVG plus real PNG files of the right sizes, all linked from the page", () => {
    const html = read("site/index.html");
    expect(html).toMatch(/<link rel="icon" href="\/favicon\.svg" type="image\/svg\+xml">/);
    expect(html).toMatch(/<link rel="apple-touch-icon" href="\/apple-touch-icon\.png">/);
    const png = (f: string) => {
      const b = readFileSync(resolve(root, "site", f));
      expect(b.subarray(1, 4).toString(), f).toBe("PNG");
      return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
    };
    expect(png("favicon-32.png")).toEqual({ w: 32, h: 32 });
    expect(png("apple-touch-icon.png")).toEqual({ w: 180, h: 180 });
    expect(png("og.png")).toEqual({ w: 1200, h: 630 });
    expect(read("site/favicon.svg")).toMatch(/<svg[^>]+viewBox="0 0 64 64"/);
  });

  it("link-preview tags use absolute URLs on the real domain (previews fail on relative ones)", () => {
    const html = read("site/index.html");
    const urls = [...html.matchAll(/<meta (?:property="og:(?:image|url)"|name="twitter:image") content="([^"]+)"/g)].map((m) => m[1]!);
    expect(urls.length).toBe(3);
    for (const u of urls) expect(u).toMatch(/^https:\/\/modedial-site\.vercel\.app\//);
    expect(html, "no leftover TODO comments in the page").not.toMatch(/<!--[\s\S]*?TODO[\s\S]*?-->/);
  });

  it("makes no external requests: no CDN scripts, no remote fonts, no analytics", () => {
    const html = read("site/index.html");
    const external = [...html.matchAll(/(?:src|href)="(https?:\/\/[^"]+)"/g)].map((m) => m[1]!).filter((u) => !/github\.com\/mac146\/modedial/.test(u));
    expect(external).toEqual([]);
    expect(html).not.toMatch(/googleapis|gstatic|googletagmanager|analytics/i);
  });

  it("states what is verified: does not claim agents it has not tested", () => {
    const html = read("site/index.html");
    expect(html).toMatch(/Tested with Claude Code, Codex CLI and opencode/);
    // The "What we don't claim" list legitimately names these claims in order to deny them, so ignore that block.
    const withoutDenials = html
      .replace(/What we don’t claim[\s\S]*?<\/ul>/, "")
      .replace("We did not benchmark whether modes improve results, and make no such claim.", "");
    expect(withoutDenials).not.toMatch(/improves? (your )?(results|code quality)|faster than|smarter|better results|outperform/i);
  });
});
