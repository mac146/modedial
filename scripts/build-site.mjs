// Generates site/modes-data.js from modes/modes.json so the landing page can never drift from the product.
// Usage: node scripts/build-site.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const modes = JSON.parse(readFileSync(resolve(root, "modes", "modes.json"), "utf8"));
const out = `// Generated by scripts/build-site.mjs from modes/modes.json. Do not edit.\nwindow.MODEDIAL_MODES = ${JSON.stringify(modes, null, 2)};\n`;
writeFileSync(resolve(root, "site", "modes-data.js"), out);
console.log(`wrote site/modes-data.js (${modes.length} modes)`);
